CATALOGS = {"en": EN, "tr": TR}
_lang: str | None = None


def current_language() -> str:
    global _lang
    if _lang is None:
        saved = QSettings().value("ui/language", "")
        if saved in CATALOGS:
            _lang = saved
        else:
            _lang = "tr" if QLocale.system().language() == QLocale.Language.Turkish else "en"
    return _lang


def set_language(lang: str) -> None:
    global _lang
    if lang in CATALOGS:
        _lang = lang
        QSettings().setValue("ui/language", lang)


def t(key: str, **kw) -> str:
    text = CATALOGS[current_language()].get(key) or EN.get(key, key)
    return text.format(**kw) if kw else text


def reason_text(key: str) -> str:
    return t(f"reason.{key}")
