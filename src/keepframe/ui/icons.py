def svg(name: str, color: str = "#ECEDEF", stroke: float = 1.6, fill: str = "none") -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{fill}" '
            f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" '
            f'stroke-linejoin="round">{_P[name]}</svg>')


@lru_cache(maxsize=512)
def pixmap(name: str, color: str, size: int = 20, dpr: float = 2.0, fill: str = "none",
           stroke: float = 1.6) -> QPixmap:
    r = QSvgRenderer(QByteArray(svg(name, color, stroke, fill).encode()))
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    r.render(p, QRectF(0, 0, size * dpr, size * dpr))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str | None = None, size: int = 20, active: str | None = None) -> QIcon:
    from .theme import T

    ic = QIcon()
    ic.addPixmap(pixmap(name, color or T["text_secondary"], size), QIcon.Normal, QIcon.Off)
    ic.addPixmap(pixmap(name, active or T["text"], size), QIcon.Active, QIcon.Off)
    ic.addPixmap(pixmap(name, active or T["text"], size), QIcon.Normal, QIcon.On)
    ic.addPixmap(pixmap(name, T["text_muted"], size), QIcon.Disabled, QIcon.Off)
    return ic


